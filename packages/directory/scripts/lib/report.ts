import type { DirectoryFile, KeysFile, Purpose } from "../../../core/src/directory/types";
import type { EvidenceCheck } from "./evidence";
import type { ManifestEntry, RobotsRecord } from "./fetcher";
import type { BuildLog } from "./merge";
import type { OperatorSource } from "./sources";

export interface ReportInput {
  directory: DirectoryFile;
  keys: KeysFile;
  log: BuildLog;
  evidence: EvidenceCheck[];
  manifest: {
    generated_at: string;
    user_agent: string;
    entries: ManifestEntry[];
    robots: RobotsRecord[];
  };
  researched: OperatorSource[];
}

const PURPOSES: Purpose[] = [
  "training",
  "search",
  "user_fetch",
  "agent",
  "preview",
  "ads",
  "other",
];

function cell(value: string | number | boolean | null | undefined): string {
  if (value === null || value === undefined || value === "") return "";
  return String(value).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

function table(
  headers: string[],
  rows: (string | number | boolean | null | undefined)[][],
): string {
  if (rows.length === 0) return "None.\n";
  const lines = [
    `| ${headers.join(" | ")} |`,
    `|${headers.map(() => "---").join("|")}|`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ];
  return `${lines.join("\n")}\n`;
}

const code = (value: string | null | undefined) => (value ? `\`${value}\`` : "");

/** docs/directory-build-report.md, regenerated by every build. */
export function buildReport(input: ReportInput): string {
  const { directory, keys, log, evidence, manifest } = input;
  const ops = directory.operators;
  const agents = ops.flatMap((op) => op.agents);
  const out: string[] = [];
  const add = (text = "") => out.push(text);

  add("# Directory build report");
  add();
  add(
    `Generated by \`pnpm directory:build\` at ${directory.generated_at} from the fetch at ${manifest.generated_at}. Do not edit by hand; rerun the pipeline instead.`,
  );
  add();
  add(
    `Directory version \`${directory.version}\`, keys version \`${keys.version}\`. Fetches identified as \`${manifest.user_agent}\` and honored robots.txt.`,
  );
  add();

  add("## Counts");
  add();
  const researchedOps = ops.filter((op) => op.coverage === "researched").length;
  add(
    table(
      ["", "Researched", "Community", "Total"],
      [
        ["Operators", researchedOps, ops.length - researchedOps, ops.length],
        [
          "Agents",
          agents.filter((agent) => agent.coverage === "researched").length,
          agents.filter((agent) => agent.coverage === "community").length,
          agents.length,
        ],
      ],
    ),
  );
  add("Agents by purpose:");
  add();
  add(
    table(
      ["Purpose", "Researched", "Community", "Total"],
      PURPOSES.map((purpose) => {
        const matching = agents.filter((agent) => agent.purpose === purpose);
        const researched = matching.filter((agent) => agent.coverage === "researched").length;
        return [code(purpose), researched, matching.length - researched, matching.length];
      }),
    ),
  );
  add(
    "Community purposes are mapped from the free-text `function` field in ai.robots.txt; each record's note keeps the original text.",
  );
  add();

  add("## Signing status");
  add();
  add(
    table(
      ["Operator", "Status", "Key directory", "Keys", "kid", "Basis", "Agents signing", "Detail"],
      log.signing.map((entry) => {
        const op = ops.find((candidate) => candidate.slug === entry.operator);
        const signing = op?.verification.signing;
        const signers = op?.agents.filter((agent) => agent.signs).map((agent) => agent.name) ?? [];
        return [
          op?.name ?? entry.operator,
          code(entry.status),
          entry.directory_url ?? "",
          entry.keys,
          signing?.kid_convention ?? "",
          entry.basis,
          signers.join(", "),
          [
            entry.detail,
            entry.rejected.length > 0 ? `Rejected: ${entry.rejected.join("; ")}` : null,
          ]
            .filter(Boolean)
            .join(" "),
        ];
      }),
    ),
  );
  add(
    "`live` means the key directory was fetched in this build and held at least one valid public key. Every key's RFC 7638 thumbprint is in `keys.json`. Community operators are `not_probed`.",
  );
  add();

  add("## IP lists");
  add();
  add(
    table(
      ["Operator", "List", "URL", "Format", "Prefixes", "Fetched", "Notes"],
      log.ipLists.map((entry) => {
        const list = ops
          .find((op) => op.slug === entry.operator)
          ?.verification.ip_lists.find((candidate) => candidate.agent === entry.id);
        const notes = [
          entry.invalid.length > 0 ? `${entry.invalid.length} invalid entries skipped` : null,
          entry.rewritten > 0 ? `${entry.rewritten} entries rewritten to normal form` : null,
          entry.duplicates > 0 ? `${entry.duplicates} duplicates removed` : null,
          list?.note ?? null,
        ].filter(Boolean);
        return [
          entry.operator,
          code(entry.id),
          entry.url,
          list?.format ?? "",
          list?.prefix_count ?? "",
          list?.fetched_at ?? "",
          notes.join(" "),
        ];
      }),
    ),
  );

  add("## Reverse DNS");
  add();
  add(
    table(
      ["Operator", "Suffixes", "Forward-confirmed", "Note"],
      ops
        .filter((op) => op.verification.reverse_dns)
        .map((op) => {
          const rule = op.verification.reverse_dns;
          return [
            op.name,
            rule?.suffixes.map(code).join(", "),
            rule?.forward_confirm ? "yes" : "no",
            rule?.note,
          ];
        }),
    ),
  );

  add("## Evidence checks");
  add();
  add(
    "Every quote, reverse DNS suffix and documented URL is looked up in the page it cites, and every user-agent token in the operator's pages, using the copies fetched for this build.",
  );
  add();
  const tally = (result: string) => evidence.filter((check) => check.result === result).length;
  add(
    table(
      ["Checked", "Verbatim", "Punctuation only", "Not found", "Page unavailable"],
      [
        [
          evidence.length,
          tally("verbatim"),
          tally("punctuation"),
          tally("not_found"),
          tally("page_unavailable"),
        ],
      ],
    ),
  );
  add(
    '"Punctuation only" means the text matches once curly quotes, dashes and Markdown emphasis are folded. "Page unavailable" means the page could not be fetched in this build, so the fact rests on the date a person checked it.',
  );
  add();
  const open = evidence.filter((check) => check.result !== "verbatim");
  if (open.length > 0) {
    add(
      table(
        ["Operator", "Fact", "Value", "Source", "Result"],
        open.map((check) => [
          check.operator,
          check.fact,
          check.value.length > 120 ? `${check.value.slice(0, 117)}...` : check.value,
          check.sourceUrl,
          check.detail ? `${check.result} (${check.detail})` : check.result,
        ]),
      ),
    );
  }

  add("## Fetch failures");
  add();
  const failures = manifest.entries.filter((entry) => entry.outcome !== "ok");
  add(
    `${manifest.entries.length - failures.length} of ${manifest.entries.length} fetches succeeded. Failures are recorded as they happened; the pipeline does not retry around robots.txt, errors or timeouts.`,
  );
  add();
  add(
    table(
      ["URL", "Kind", "Operator", "Outcome", "Detail"],
      failures.map((entry) => [
        entry.url,
        entry.kind,
        entry.operator,
        code(entry.outcome),
        entry.detail,
      ]),
    ),
  );
  const robotsTrouble = manifest.robots.filter((record) => record.outcome === "unreachable");
  if (robotsTrouble.length > 0) {
    add("robots.txt files that could not be read (treated as disallow all, per RFC 9309):");
    add();
    add(
      table(
        ["Origin", "Detail"],
        robotsTrouble.map((record) => [record.origin, record.detail]),
      ),
    );
  }

  add("## Merging");
  add();
  add(
    `- ${log.merged.length} ai.robots.txt entries matched a researched agent and were merged into it (researched facts win).`,
  );
  add(
    `- ${log.claimed.length} ai.robots.txt entries were kept as community agents of a researched operator.`,
  );
  add(
    `- ${log.collapsed.length} spellings were collapsed into another record (case or version suffix): ${log.collapsed.map((entry) => `\`${entry.dropped}\` into \`${entry.kept}\``).join(", ") || "none"}.`,
  );
  add(
    `- Entries listed in \`community_agents\` but missing from robots.json: ${log.missingClaims.map((entry) => `\`${entry.community}\` (${entry.operator})`).join(", ") || "none"}.`,
  );
  const byName = log.claimed.filter((entry) => entry.how === "operator name");
  if (byName.length > 0) {
    add(
      `- Attached by operator name only, worth adding to the operator's \`community_agents\`: ${byName.map((entry) => `\`${entry.community}\` (${entry.operator})`).join(", ")}.`,
    );
  }
  add();
  add(
    table(
      ["ai.robots.txt entry", "Merged into"],
      log.merged.map((entry) => [code(entry.community), `${entry.operator}/${entry.agent}`]),
    ),
  );

  add("## Researched operator notes");
  add();
  for (const source of input.researched) {
    const op = ops.find((candidate) => candidate.slug === source.slug);
    const notes = [
      source.note,
      op?.verification.signing.note ? `Signing: ${op.verification.signing.note}` : null,
      ...source.agents.filter((agent) => agent.note).map((agent) => `${agent.name}: ${agent.note}`),
    ].filter(Boolean);
    add(`### ${source.name}`);
    add();
    add(
      `Checked on ${source.checked_on}. ${source.agents.length} researched ${source.agents.length === 1 ? "agent" : "agents"}.`,
    );
    add();
    for (const note of notes) add(`- ${cell(note)}`);
    if (notes.length > 0) add();
  }
  return `${out
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()}\n`;
}
